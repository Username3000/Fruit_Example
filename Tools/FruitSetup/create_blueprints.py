import unreal, json
from pathlib import Path

root = Path(unreal.Paths.project_dir()).resolve()
bp_path = '/Game/Root/Blueprints/B_FruitBase'
bp = unreal.load_asset(bp_path)
library = unreal.BlueprintEditorLibrary
pinlib = unreal.BlueprintGraphPinLibrary
function_name = 'SpawnFruitPieces'
variables = list(library.list_member_variable_names(bp, include_inherited_members=False))
if 'FruitBurstSystem' not in variables:
    assert library.add_member_variable(bp, 'FruitBurstSystem', library.get_object_reference_type(unreal.NiagaraSystem))
    library.set_blueprint_variable_category(bp, 'FruitBurstSystem', 'Fruit|Effects')
    library.set_blueprint_variable_instance_editable(bp, 'FruitBurstSystem', True)
library.compile_blueprint(bp)
cdo = unreal.get_default_object(library.generated_class(bp))
cdo.set_editor_property('FruitBurstSystem', unreal.load_asset('/Game/Root/Assets/VFX/Fruits/NS_FruitPieces_Apple'))

graph = library.find_graph(bp, function_name)
editor = unreal.BlueprintGraphEditor.get_graph_editor(graph) if graph else unreal.BlueprintGraphEditor.create_and_edit_function_graph(bp, function_name)
# This graph is generated by this task; permit resuming a partially completed build.
editor.remove_nodes([node for node in editor.list_all_nodes() if not isinstance(node, unreal.K2Node_FunctionEntry)])

def call(path, x, y):
    node = editor.add_call_function_node(path)
    assert node, path
    library.set_node_pos(node, unreal.IntPoint(x,y))
    return node

def input_pin(node,name):
    pin=library.find_input_pin(node,name)
    assert pin.is_valid(), node.get_name()+'.'+name
    return pin

def output_pin(node,name):
    pin=library.find_output_pin(node,name)
    assert pin.is_valid(), node.get_name()+'.'+name
    return pin

def link(a,b):
    assert a.try_create_connection(b), str(a.get_pin_name())+' -> '+str(b.get_pin_name())

def literal(node,name,value):
    assert input_pin(node,name).set_pin_value(value), name+':'+value

system_get=editor.add_get_member_variable_node('FruitBurstSystem')
library.set_node_pos(system_get,unreal.IntPoint(0,180))
valid=call('/Script/Engine.KismetSystemLibrary.IsValid',220,180)
link(output_pin(system_get,'FruitBurstSystem'),input_pin(valid,'Object'))
branch=editor.add_branch_node()
library.set_node_pos(branch,unreal.IntPoint(240,0))
link(editor.find_graph_entry_pin(),library.find_execute_pin(branch))
link(output_pin(valid,'ReturnValue'),library.find_condition_pin(branch))

mesh_get=editor.add_get_member_variable_node('Mesh')
library.set_node_pos(mesh_get,unreal.IntPoint(0,400))
bounds=call('/Script/Engine.KismetSystemLibrary.GetComponentBounds',230,400)
link(output_pin(mesh_get,'Mesh'),input_pin(bounds,'Component'))
spawn=call('/Script/Niagara.NiagaraFunctionLibrary.SpawnSystemAtLocation',580,0)
link(library.find_then_pin(branch),library.find_execute_pin(spawn))
link(output_pin(system_get,'FruitBurstSystem'),input_pin(spawn,'SystemTemplate'))
link(output_pin(bounds,'Origin'),input_pin(spawn,'Location'))
literal(spawn,'bAutoActivate','false')
literal(spawn,'bAutoDestroy','true')
literal(spawn,'bPreCullCheck','false')
literal(spawn,'Scale','1,1,1')

component_valid=call('/Script/Engine.KismetSystemLibrary.IsValid',850,450)
link(output_pin(spawn,'ReturnValue'),input_pin(component_valid,'Object'))
component_branch=editor.add_branch_node()
library.set_node_pos(component_branch,unreal.IntPoint(950,0))
link(library.find_then_pin(spawn),library.find_execute_pin(component_branch))
link(output_pin(component_valid,'ReturnValue'),library.find_condition_pin(component_branch))
velocity=editor.add_get_member_variable_node('CurrentVelocity')
library.set_node_pos(velocity,unreal.IntPoint(1030,400))
set_velocity=call('/Script/Niagara.NiagaraComponent.SetNiagaraVariableVec3',1250,0)
link(library.find_then_pin(component_branch),library.find_execute_pin(set_velocity))
link(output_pin(spawn,'ReturnValue'),library.find_self_pin(set_velocity))
literal(set_velocity,'InVariableName','User.InheritedVelocity')
link(output_pin(velocity,'CurrentVelocity'),input_pin(set_velocity,'InValue'))
activate=call('/Script/Engine.ActorComponent.Activate',1650,0)
link(library.find_then_pin(set_velocity),library.find_execute_pin(activate))
link(output_pin(spawn,'ReturnValue'),library.find_self_pin(activate))
literal(activate,'bReset','true')
editor.add_comment_node('Spawn detached pieces at the mesh center. Set world velocity BEFORE activation; destroy the fruit afterward.',unreal.Vector2D(-80,-150),unreal.Vector2D(2050,850))
library.compile_blueprint(bp)
assert not editor.list_nodes_with_errors(), 'SpawnFruitPieces failed to compile'

damage=unreal.BlueprintGraphEditor.get_graph_editor_by_name(bp,'Damage')
destroy=next(node for node in damage.list_all_nodes() if str(library.get_node_title(node))=='Destroy Actor')
existing=[node for node in damage.list_all_nodes() if str(library.get_node_title(node)).replace(' ','')=='SpawnFruitPieces']
if not existing:
    incoming=list(library.find_execute_pin(destroy).list_connected_pins())
    assert len(incoming)==1, 'Unexpected Damage graph; preserve existing logic'
    cls=library.generated_class(bp)
    effect_call=damage.add_call_function_node(cls.get_path_name()+'.'+function_name)
    assert effect_call
    library.find_execute_pin(destroy).break_pin_links()
    link(incoming[0],library.find_execute_pin(effect_call))
    link(library.find_then_pin(effect_call),library.find_execute_pin(destroy))
    library.set_node_pos(effect_call,unreal.IntPoint(250,0))
    library.set_node_pos(destroy,unreal.IntPoint(550,0))
    damage.add_comment_node('On damage: burst with CurrentVelocity, then destroy this fruit.',unreal.Vector2D(-80,-120),unreal.Vector2D(1000,380))
library.compile_blueprint(bp)
assert not damage.list_nodes_with_errors()
unreal.EditorAssetLibrary.save_loaded_asset(bp)

folder='/Game/Root/Blueprints/Fruits'
unreal.EditorAssetLibrary.make_directory(folder)
subsystem=unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)
result=[]
for fruit in ['Apple','Banana','Coconut','Orange','Pear','Pineapple','Strawberry','Watermelon']:
    path=folder+'/B_Fruit_'+fruit
    child=unreal.load_asset(path) if unreal.EditorAssetLibrary.does_asset_exist(path) else None
    if not child:
        factory=unreal.BlueprintFactory()
        factory.set_editor_property('parent_class',library.generated_class(bp))
        child=unreal.AssetToolsHelpers.get_asset_tools().create_asset('B_Fruit_'+fruit,folder,unreal.Blueprint,factory)
    assert child
    library.compile_blueprint(child)
    components=[]
    for handle in subsystem.k2_gather_subobject_data_for_blueprint(child):
        data=unreal.SubobjectDataBlueprintFunctionLibrary.get_data(handle)
        obj=unreal.SubobjectDataBlueprintFunctionLibrary.get_object_for_blueprint(data,child)
        if isinstance(obj,unreal.StaticMeshComponent) and obj not in components:
            components.append(obj)
    assert len(components)==1,fruit+': expected one inherited mesh'
    mesh=unreal.load_asset('/Game/Root/Assets/Meshes/Fruits/SM_'+fruit)
    components[0].set_static_mesh(mesh)
    components[0].set_editor_property('override_materials',[])
    components[0].set_relative_scale3d(unreal.Vector(2.5,2.5,2.5))
    library.compile_blueprint(child)
    child_cdo=unreal.get_default_object(library.generated_class(child))
    child_cdo.set_editor_property('FruitBurstSystem',unreal.load_asset('/Game/Root/Assets/VFX/Fruits/NS_FruitPieces_'+fruit))
    if 'FruitVisualRotationEnabled' in set(map(str,library.list_member_variable_names(child,include_inherited_members=True))):
        child_cdo.set_editor_property('FruitVisualRotationEnabled',True)
    unreal.EditorAssetLibrary.save_loaded_asset(child)
    result.append({'blueprint':path,'mesh':mesh.get_path_name(),'niagara':child_cdo.get_editor_property('FruitBurstSystem').get_path_name()})
    print('FRUIT_BLUEPRINT:' + json.dumps(result[-1]))

(root/'Saved/MCP/fruit-blueprints.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
library.refresh_all_open_blueprint_editors()
unreal.EditorAssetLibrary.sync_browser_to_objects([row['blueprint'] for row in result])
print('FRUIT_BLUEPRINTS_READY')
calibration=root/'Tools/FruitSetup/proportion_pieces.py'
exec(compile(calibration.read_text(encoding='utf-8'),str(calibration),'exec'),{'__name__':'__main__'})
